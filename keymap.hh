static inline uint8_t usb_to_sun(uint32_t usage) {
  return (usage < sizeof(usb_to_sun_tab)) ? usb_to_sun_tab[usage] : 0;
}

/* a typed ASCII character as a USB usage + whether it needs shift (US
 * layout); usage 0 = not typeable */
static inline uint32_t ascii_to_usb(char c, bool *shift) {
  static const char unshifted[] = "1234567890-=[]\\;'`,./";
  static const char shifted[]   = "!@#$%^&*()_+{}|:\"~<>?";
  static const uint8_t usage[]  = {0x1e, 0x1f, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27,
				   0x2d, 0x2e, 0x2f, 0x30, 0x31, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38};
  static_assert(sizeof(unshifted) == sizeof(usage) + 1 and sizeof(shifted) == sizeof(usage) + 1,
		"ascii_to_usb tables out of step");
  *shift = false;
  if(c >= 'a' and c <= 'z') {
    return 0x04 + (c - 'a');
  }
  if(c >= 'A' and c <= 'Z') {
    *shift = true;
    return 0x04 + (c - 'A');
  }
  switch(c)
    {
    case '\n': return 0x28;   /* return */
    case ' ':  return 0x2c;
    case '\t': return 0x2b;
    case 0x7f: return 0x2a;   /* backspace */
    case 0x1b: return 0x29;   /* escape */
    default:   break;
    }
  for(uint32_t i = 0; i < sizeof(usage); i++) {
    if(c == unshifted[i]) {
      return usage[i];
    }
    if(c == shifted[i]) {
      *shift = true;
      return usage[i];
    }
  }
  return 0;
}

